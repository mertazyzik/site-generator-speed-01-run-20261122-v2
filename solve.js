// Fast drop-in for makefun-site 1.0.0 (site-generator-speed-01-run-20261122).
//
// Written fresh in-session: a reimplementation of makefun-site's build with
// the same answers, byte for byte, but without the reference's per-character
// loops. The hot paths are what change:
//   - inline Markdown is scanned in bulk: plain runs are sliced out whole
//     between the characters that can mean something, instead of one regex
//     replace per character;
//   - the block lexer dispatches on a line's first character and only runs
//     a block's regex when the line could be that block;
//   - slugify takes an ASCII fast path (NFKD is the identity on ASCII and
//     no combining mark is ASCII) and memoizes repeated titles/tags;
//   - templates render into chunk arrays joined once, instead of += per node;
//   - word counting scans without building an array of the words.
// Nothing is cached from one case to the next: every per-run cache below is
// created inside run() and dropped with it.

